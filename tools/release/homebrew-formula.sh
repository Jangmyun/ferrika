#!/usr/bin/env bash
# Writes the Homebrew formula for a release to stdout.
#
#   tools/release/homebrew-formula.sh <version> <dist-dir>
#
# <dist-dir> holds the release archives and their .sha256 files, named
# ferrika-v<version>-<target>.tar.gz(.sha256), for the four targets below.
# The release workflow commits the output to Formula/ferrika.rb in
# https://github.com/Jangmyun/homebrew-tap.
set -euo pipefail

if [ "$#" -ne 2 ]; then
  echo "usage: $0 <version> <dist-dir>" >&2
  exit 2
fi
version="$1"
dist="$2"
base="https://github.com/Jangmyun/ferrika/releases/download/v${version}"

# Prints the sha256 of one target's archive; fails if it is missing.
sha() {
  local file="${dist}/ferrika-v${version}-$1.tar.gz.sha256"
  if [ ! -f "$file" ]; then
    echo "missing ${file}" >&2
    exit 1
  fi
  cut -d ' ' -f 1 "$file"
}

mac_arm=$(sha aarch64-apple-darwin)
mac_intel=$(sha x86_64-apple-darwin)
linux_arm=$(sha aarch64-unknown-linux-gnu)
linux_intel=$(sha x86_64-unknown-linux-gnu)

cat <<EOF
# Generated by tools/release/homebrew-formula.sh in
# https://github.com/Jangmyun/ferrika. Do not edit by hand.
class Ferrika < Formula
  desc "Single-binary Kafka command-line client, no JVM"
  homepage "https://github.com/Jangmyun/ferrika"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "${base}/ferrika-v${version}-aarch64-apple-darwin.tar.gz"
      sha256 "${mac_arm}"
    end
    on_intel do
      url "${base}/ferrika-v${version}-x86_64-apple-darwin.tar.gz"
      sha256 "${mac_intel}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/ferrika-v${version}-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "${linux_arm}"
    end
    on_intel do
      url "${base}/ferrika-v${version}-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "${linux_intel}"
    end
  end

  def install
    bin.install "ferrika"
  end

  test do
    assert_match "ferrika #{version}", shell_output("#{bin}/ferrika --version")
  end
end
EOF
